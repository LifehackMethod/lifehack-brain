#!/bin/bash
# LHB fire-journal (B4.1): observes only; never alters this hook's decision/exit/stdout/stderr.
_lhb_src="${BASH_SOURCE[0]}"; case "$_lhb_src" in */*) _lhb_dir="${_lhb_src%/*}" ;; *) _lhb_dir=. ;; esac; . "$_lhb_dir/lib/journal.sh" 2>/dev/null || lhb_journal_fire() { :; }
trap 'lhb_journal_fire "$?" "guard_organism_map.sh" "PreToolUse" "Write|Edit|MultiEdit" 2>/dev/null || true' EXIT
# ── LLM CONTEXT ──────────────────────────────────────────────────────────────
# WHY: `system/organism/` is the description this repository keeps of its OWN attack surface —
#      `manual.md` (the reference index), `map-format-specs.md` (the label criteria), and the
#      `elements/*.md` encyclopedia — AND it is the ground truth that the honesty-label checker
#      (`system/tools/organism/label_checker.py`) grades every guard against. Nothing downstream
#      re-reads it to see whether it still describes reality, so a single full-content overwrite
#      could replace the whole map, or flip every maturity label to LIVE, in one shot, and the
#      system would report itself healthy while being blind to itself.
#      THE LOCAL INCIDENT, and it is the reason this file exists at this destination:
#      this guard was DROPPED during the port on one stated justification —
#      `system/tools/organism/label_manifest.yaml` recorded that "system/organism/ does not exist
#      in this repo at all (confirmed absent)". Phase 9 landed that whole tree on 2026-08-15:
#      `manual.md` (1206 lines), `map-format-specs.md`, and 42 files under `elements/`. The premise
#      died and nothing replaced it, which left the worst of the three available states — SIX
#      SHIPPED files described the organism tree as write-guarded while nothing guarded it —
#      `manual.md` (4 occurrences) and 5 `elements/*.md` (archivist · claude-md-pyramid ·
#      hook-plane · label-checker · pulse-cron), counted with grep rather than by hand.
#      `map-format-specs.md` §6 (item 4, the write-guard clause) was the ONE file that described the guarantee and then honestly
#      admitted it was unenforced here — which is why the gap was findable at all. A protection that is
#      DOCUMENTED BUT ABSENT is the exact defect class this migration kept finding, and the house
#      rule ratified the same day (`T9.11b`, `system/build-rules-index.md`) names it.
#      The donor also measured the scope error worth inheriting: the guard originally covered only
#      2 of 51 map files and named `elements/` nowhere at all, while the always-loaded map pointed
#      at the elements as THE live map. The elements carry the routing-critical `generated_from`
#      field and the INTENT / CURRENT-VS-TARGET fields the map honesty rests on — they were the
#      unguarded 96%. They are in scope here from the first line.
# GUARDS: a full-content `Write` (whole-file overwrite) of `canon/manual.md`,
#      `canon/map-format-specs.md`, or ANY `system/organism/elements/*.md` INSIDE THIS
#      REPOSITORY. Paths are resolved to their real location first, so a relative path, a `..`
#      segment or a symlink cannot name a protected file in a spelling the comparison misses —
#      the donor version matched a raw glob and a plain relative path walked straight past it.
#      Surgical `Edit` calls to those files are NOT guarded, deliberately: that is the normal
#      authoring path.
#      SINCE 2026-11-16: `canon/components/*.md` pages (moved from system/organism/components/ on 2026-11-22) carry TWO machine-only blocks,
#      fenced AS-BUILT and STATUS, regenerated by
#      `python3 system/tools/organism/component_page.py asbuilt|stamp <page>`. A hand edit inside
#      either fence is overwritten and reported on the next run. A whole-file Write of a component
#      page is signed (refused here); an Edit/MultiEdit is signed when its old_string or
#      new_string touches the fenced content (contains the AS-BUILT:/STATUS: markers or any line
#      that appears between the fences in the current file); an Edit confined to the human parts
#      (intent, scope, interfaces) passes.
# REDIRECT: author manual.md / map-format-specs.md / elements/*.md with SURGICAL Edits
#      (old_string -> new_string). Those are ALLOWED.
#      Maturity labels are machine-owned: run
#      `python3 system/tools/organism/label_checker.py write-labels` to recompute them; never
#      hand-write a LIVE. If a whole file genuinely must be regenerated, do it through Bash with a
#      human OK, which is deliberate and visible in a way a tool call is not.
#      For a component page: regenerate the machine blocks with
#      `python3 system/tools/organism/component_page.py asbuilt|stamp <page>`; to change the HUMAN
#      parts (intent, scope, interfaces) edit the page with Bash and a human OK, or regenerate.
# SIGNPOST: the RULE lives in `canon/map-format-specs.md` §6 item 4 (the write-guard clause;
#      items 2-3 there carry the same-commit and git-tracked rules). Change what is
#      protected THERE, with sign-off from the person who owns this repository, then update this
#      guard and its registration in `.claude/settings.json`. Hook mechanics:
#      `canon/hook-contract.md`; the decision layer: `canon/hook-sop.md`.
# FAIL_POSTURE: closed — an unreadable or unparseable payload DENIES. Since 2026-11-16 the
#      registration routes EVERY Edit and MultiEdit through this hook (matcher Write|Edit|MultiEdit),
#      so the hook must exit 0 fast for any path outside system/organism/; the closed posture also
#      covers an Edit to a component page whose fenced-content check itself could not be computed.
#      Denying on a malformed message costs one retry and cannot wall off the session.
# KNOWN LIMITS (stated, not hidden — an honest gap beats a false guarantee):
#   1. BASH WRITES ARE NOT COVERED. A heredoc, `tee`, `cp` or a `>` redirect aimed at a map file
#      bypasses this guard entirely, because it matches a typed tool. That is the same accepted
#      gap `guard_write_paths.sh` carries and records. It is also, deliberately, the REDIRECT above:
#      regenerating a whole map file through the shell is meant to stay possible for a human.
#   2. LABEL WRITES BY THE CHECKER ITSELF ARE NOT COVERED. `label_checker.py write-labels` writes
#      through Python, not the Write tool, so it is not intercepted. That is correct — it is the
#      sanctioned writer, and it is the thing this guard redirects people TO.
#   3. COMPONENT FENCE DETECTION IS LINE- AND MARKER-BASED, NOT PARSE-EXACT. The pass/sign decision
#      for an Edit to a component page looks for the AS-BUILT:/STATUS: markers and for any
#      non-trivial line that appears between the fences in the CURRENT file; a hand edit that
#      rewords a fenced line so it no longer matches verbatim can slip past this sign — and is
#      still caught by component_page.py itself, which overwrites and reports it on the next run.
#      Bash writes to component pages bypass this guard entirely (limit 1 above).
# UPDATED: 2026-11-22 (canon-in-one-place move: manual.md, map-format-specs.md and the component pages moved
#      to canon/; system/organism/elements/ stayed. Case arms, the component-fence path and the deny texts repointed.)
# UPDATED: 2026-11-16 (component pages: a SIGN, not a hard block, for
#      system/organism/components/*.md (now canon/components/*.md); registration widened from Write to
#      Write|Edit|MultiEdit; outside-fence Edits to a component page pass, inside-fence
#      ones are signed). Previous: 2026-08-15 (ported from the donor system; scope
#      re-derived against this repo — 42
#      elements here, not 49; path matching rebuilt on realpath + this repo root rather than a
#      glob; deny channel confirmed against the house standard in `canon/hook-contract.md`)
# ─────────────────────────────────────────────────────────────────────────────
# guard_organism_map.sh — PreToolUse hook (matcher: Write|Edit|MultiEdit).
#
# ── DENY CHANNEL — verified, not assumed. ────────────────────────────────────────────────
# The house standard here is deny text on STDERR with `exit 2` (`canon/hook-contract.md`,
# "Canonical Deny Format"), which is what the live fleet uses — see `guard_canon_write.sh`, whose
# every deny path is exactly this shape. The dead channel this repo has on record is a PreToolUse
# hook that prints and then `exit 0`s (`canon/hook-sop.md`, the `guard_web_search.sh` entry:
# "the warning was security theater the model never saw"). That failure is about the ALLOW path.
# A BLOCK at `exit 2` is read. `hookSpecificOutput.permissionDecision` is NOT used here:
# `hook-contract.md` rules it out for the BLOCK case by name, and this hook has no ALLOW notice.
#
# ⚠ THE DENY JSON MUST RE-PARSE. Measured during this port, before registration: the deny
# message wrapped a command in BACKTICKS, and the bash-escaping needed to survive a double-quoted
# string emitted a literal `\` + backtick into the JSON string -- an invalid escape. json.load()
# refused it, exit 2 still fired, and the guard would have blocked with a message NEITHER channel
# could render: silently DARK, exactly the failure `canon/hook-sop.md` §4 names ("re-parse
# the deny JSON afterwards"). An exit-code-only test scores this a PASS. ⛔ So: no backticks in
# the deny text, and re-run `python3 -c 'import json,sys; json.load(sys.stdin)'` on the STDERR of
# every deny path after any edit to this file.
set -uo pipefail

deny() {
  printf '%s\n' "$1" >&2
  exit 2
}

_HOOKDIR="$(cd "$(dirname "$0")" 2>/dev/null && pwd -P)"
# See system/hooks/lib/winpath_fold.sh: on Windows, `pwd -P` and Python's os.path.realpath spell
# the same directory two different ways, so REPO_REAL and FP below (both built through one or the
# other) would never compare equal without this. Fails CLOSED if the lib cannot be loaded, same as
# every other unreadable-input case in this guard.
. "$_HOOKDIR/lib/winpath_fold.sh" 2>/dev/null || deny '{"decision":"block","reason":"BLOCKED: guard_organism_map could not load lib/winpath_fold.sh, the path-form normaliser its repo-root comparison depends on -- failing CLOSED. REDIRECT: confirm system/hooks/lib/winpath_fold.sh exists and is readable, then retry."}'
REPO="${CLAUDE_PROJECT_DIR:-${_HOOKDIR%/system/hooks}}"

INPUT=$(cat 2>/dev/null) || deny '{"decision":"block","reason":"BLOCKED: guard_organism_map could not read its input, so it is failing closed. WHY: this guard stands over system/organism/ — the description this repository keeps of its own attack surface, and the ground truth the honesty-label checker grades against. An unreadable payload and a harmless one must never look the same. REDIRECT: retry the write; author the map with surgical Edits (old_string -> new_string), which are allowed and are the normal authoring path. RULE: canon/map-format-specs.md section 6 item 4 (the write-guard clause; items 2-3 carry the same-commit and git-tracked rules)."}'

export _ORG_REPO="$REPO"

# Resolve the target to its REAL path before comparing, and resolve the repo the same way, so both
# sides of the comparison are in one form. A relative path, a `..` segment or a symlink would each
# otherwise be a spelling of a protected file that a string test does not recognise.
read -r TOOL CONTENT_PRESENT HIT FP <<EOF2
$(printf '%s' "$INPUT" | python3 -c "
import sys, json, os, re
try:
    d = json.load(sys.stdin)
    ti = d.get('tool_input', {}) or {}
    tool = (d.get('tool_name') or '').strip() or '__NONE__'
    has = '1' if ti.get('content') is not None else '0'
    p = ti.get('file_path') or ti.get('path') or ''
    hit = '0'
    if p:
        base = os.environ.get('_ORG_REPO') or os.getcwd()
        if not os.path.isabs(p):
            p = os.path.join(base, p)
        p = os.path.realpath(p)
        comp = os.path.join(os.path.realpath(base), 'canon', 'components')
        # On darwin the filesystem is case-insensitive: fold both sides for the
        # component-page test, keep the original p for reading the file (fix 11).
        if os.uname().sysname == 'Darwin':
            pp, cc = p.lower(), comp.lower()
        else:
            pp, cc = p, comp
        if tool in ('Edit', 'MultiEdit') and (pp == cc or (pp.startswith(cc + os.sep) and pp.endswith('.md'))):
            if tool == 'MultiEdit':
                edits = list(ti.get('edits') or [])
            else:
                edits = [{'old_string': ti.get('old_string') or '', 'new_string': ti.get('new_string') or ''}]
            try:
                content = open(p, encoding='utf-8', errors='replace').read()
                lines = content.split('\n')
            except Exception:
                lines = None
            # Fence ranges: a BEGIN line through its matching END line, INCLUSIVE
            # (0-based indices). A BEGIN with no END reaches the end of the file.
            ranges = []
            if lines is not None:
                start = None
                for i, ln in enumerate(lines):
                    if 'AS-BUILT:BEGIN' in ln or 'STATUS:BEGIN' in ln:
                        if start is None:
                            start = i
                    elif ('AS-BUILT:END' in ln or 'STATUS:END' in ln) and start is not None:
                        ranges.append((start, i))
                        start = None
                if start is not None:
                    ranges.append((start, len(lines) - 1))
            for e in edits:
                old = e.get('old_string') or ''
                if old == '':
                    continue  # an empty old_string covers no line range
                rng = None
                if lines is not None:
                    idx = content.find(old)
                    if idx >= 0:
                        first = content[:idx].count('\n')
                        rng = (first, first + old.count('\n'))
                if rng is None:
                    # old_string is not in the file: it cannot be shown to be
                    # outside the fences, so SIGN -- fail closed (fix 8).
                    hit = '1'
                    break
                if any(not (rng[1] < r0 or rng[0] > r1) for (r0, r1) in ranges):
                    hit = '1'
                    break
    # FP is printed LAST and read as the remainder of the line, so a path
    # containing spaces survives the shell read (fix 9).
    print(tool, has, hit, p)
except Exception:
    print('__ERR__ __ERR__ __ERR__ __ERR__')
" 2>/dev/null)
EOF2

[ "$TOOL" = "__ERR__" ] && deny '{"decision":"block","reason":"BLOCKED: guard_organism_map could not parse the tool call, so it is failing closed. WHY: this guard stands over system/organism/ -- the description this repository keeps of its own attack surface, and the ground truth the honesty-label checker grades against -- and, since 2026-11-16, over the machine-only fenced blocks of the component pages. A payload it cannot inspect must not pass. REDIRECT: retry the write; author the map with surgical Edits (old_string -> new_string), which are allowed and are the normal authoring path. RULE: canon/map-format-specs.md section 6 item 4 (the write-guard clause; items 2-3 carry the same-commit and git-tracked rules)."}'

[ -n "$FP" ] || exit 0

REPO_REAL=$(python3 -c "
import os, sys
try: print(os.path.realpath(sys.argv[1]))
except Exception: print('')" "$REPO" 2>/dev/null)
[ -n "$REPO_REAL" ] || exit 0     # cannot locate the repo; this guard has nothing to say
REPO_REAL="$(_winfold "$REPO_REAL")"
FP="$(_winfold "$FP")"
# Keep the original spellings for the deny message; compare with folded copies.
REPO_REAL_ORIG="$REPO_REAL"
FP_ORIG="$FP"
case "$(uname -s)" in
  Darwin)
    # FIX 11: on darwin the filesystem is case-insensitive, so canon/COMPONENTS/
    # names the same directory as canon/components/. Fold both sides before the
    # glob comparison, or a case-variant spelling walks straight past the guard.
    REPO_REAL=$(printf '%s' "$REPO_REAL" | tr '[:upper:]' '[:lower:]')
    FP=$(printf '%s' "$FP" | tr '[:upper:]' '[:lower:]')
    ;;
esac

# A SIGN is the component-page deny: it refuses the call and re-teaches the boundary, but the
# human parts of the page remain editable by design (Bash + a human OK, or regenerate).
deny_component() {
  FP_REL="${FP_ORIG#"$REPO_REAL_ORIG"/}"
  _MSG="$(ORG_REASON="$1" ORG_FP="$FP_REL" python3 -c '
import json, os
print(json.dumps({"decision": "block", "reason":
  "BLOCKED (SIGN): " + os.environ["ORG_REASON"] + " -- " + os.environ["ORG_FP"] +
  ". WHY: a component page under canon/components/ carries two machine-only fenced blocks, AS-BUILT and STATUS, which are regenerated by python3 system/tools/organism/component_page.py asbuilt or stamp <page>; a hand edit inside either fence is overwritten and reported on the next run, so hand-writing that part is overwritten work. REDIRECT: regenerate the machine blocks with python3 system/tools/organism/component_page.py asbuilt|stamp <page>; to change the human parts (intent, scope, interfaces) edit the page with Bash and a human OK, or regenerate. RULE: canon/hook-sop.md and canon/hook-contract.md; a change to this rule goes to the person."}))')"
  deny "$_MSG"
}

case "$FP" in
  "$REPO_REAL"/canon/manual.md \
  |"$REPO_REAL"/canon/map-format-specs.md \
  |"$REPO_REAL"/system/organism/elements/*.md)
    # UNCHANGED from 2026-08-15: a wholesale Write is denied; Edits to these files still pass.
    [ "$TOOL" = "Write" ] || exit 0
    [ "$CONTENT_PRESENT" = "1" ] || exit 0
    FP_REL="${FP_ORIG#"$REPO_REAL_ORIG"/}"
    _MSG="$(ORG_FP="$FP_REL" python3 -c '
import json, os
print(json.dumps({"decision": "block", "reason":
  "BLOCKED: a wholesale Write (full-file overwrite) of the self-schematic map -- " + os.environ["ORG_FP"] +
  ". WHY: system/organism/ is the description this repository keeps of its OWN attack surface AND the ground truth the honesty-label checker (system/tools/organism/label_checker.py) grades every guard against. Nothing downstream re-reads it, so one full-content overwrite could replace the whole map, or flip every maturity label to LIVE, in a single shot -- and the system would go on reporting itself healthy while blind to itself. REDIRECT: author the map with SURGICAL Edits (old_string -> new_string). Edits are ALLOWED and are the normal authoring path. Maturity labels are machine-owned: run: python3 system/tools/organism/label_checker.py write-labels -- to recompute them, never hand-write a LIVE. If a whole file genuinely must be regenerated, do it through Bash with a human OK. RULE: canon/map-format-specs.md section 6 item 4 (the write-guard clause; items 2-3 carry the same-commit and git-tracked rules). To change what is protected, change it THERE with sign-off, then update this guard and its registration."}))')"
    deny "$_MSG"
    ;;
  "$REPO_REAL"/canon/components/*.md)
    case "$TOOL" in
      Write)
        [ "$CONTENT_PRESENT" = "1" ] || exit 0
        deny_component "a wholesale Write (full-file overwrite) of a component page"
        ;;
      Edit|MultiEdit)
        # HIT was computed in the extraction above: 1 when an old_string or new_string carries the
        # AS-BUILT:/STATUS: markers or any line that appears between the fences in the current
        # file. An Edit confined to the human parts passes; FAIL_POSTURE above covers the case
        # where the check itself could not be computed.
        if [ "$HIT" = "1" ]; then
          deny_component "an Edit or MultiEdit reaching into the machine-only AS-BUILT or STATUS fenced blocks"
        fi
        exit 0
        ;;
      *) exit 0 ;;
    esac
    ;;
  *) exit 0 ;;
esac

exit 0
