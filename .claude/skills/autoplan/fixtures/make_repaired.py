def build():
    with open(BROKEN, encoding="utf-8") as f:
        text = f.read()
    for tid, label, old, new in FIXES:
        n = text.count(old)
        if n != 1:
            raise AssertionError(
                f"fix for {tid} ({label}) matched {n} times, expected exactly 1 — "
                f"broken.plan.md has drifted from make_repaired.py's FIXES list; "
                f"update FIXES to match the current broken.plan.md")
        text = text.replace(old, new, 1)
    return text


def main():
    out = build()
    with open(REPAIRED, "w", encoding="utf-8") as f:
        f.write(out)
    print(f"wrote {REPAIRED} ({len(FIXES)} fixes applied)")


if __name__ == "__main__":
    sys.exit(main())
